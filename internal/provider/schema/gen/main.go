func main() {
	err := run()
	if err != nil {
		fmt.Fprintln(os.Stderr, "generating provider schema:", err)
		os.Exit(1)
	}
}

func run() (err error) {
	const providersDir = "../providers"
	entries, err := os.ReadDir(providersDir)
	if err != nil {
		return fmt.Errorf("reading providers directory: %w", err)
	}

	var generated []generatedProvider
	fset := token.NewFileSet()
	for _, entry := range entries {
		if !entry.IsDir() {
			continue
		}
		dirName := entry.Name()
		filePath := filepath.Join(providersDir, dirName, "provider.go")
		file, err := parser.ParseFile(fset, filePath, nil, 0)
		if err != nil {
			return fmt.Errorf("parsing %s: %w", filePath, err)
		}

		fields, err := extractFields(file)
		if err != nil {
			return fmt.Errorf("extracting fields of provider %s: %w", dirName, err)
		}

		name := dirName
		if mapped, ok := providerNames[dirName]; ok {
			name = mapped
		}
		label := providerLabels[dirName]
		if label == "" {
			label = name
		}
		docsPath := dirName + ".md"
		if mapped, ok := docsPaths[dirName]; ok {
			docsPath = mapped
		}

		generated = append(generated, generatedProvider{
			Name:     name,
			Label:    label,
			DocsPath: docsPath,
			Fields:   fields,
		})
	}

	sort.Slice(generated, func(i, j int) bool {
		return generated[i].Name < generated[j].Name
	})

	var buffer bytes.Buffer
	buffer.WriteString("// Code generated by go generate; DO NOT EDIT.\n")
	buffer.WriteString("// Regenerate with: go generate ./internal/provider/schema\n\n")
	buffer.WriteString("package schema\n\n")
	buffer.WriteString("var providers = []Provider{\n")
	for _, provider := range generated {
		fmt.Fprintf(&buffer, "\t{\n\t\tName: %s,\n\t\tLabel: %s,\n\t\tDocsPath: %s,\n",
			strconv.Quote(provider.Name), strconv.Quote(provider.Label),
			strconv.Quote(provider.DocsPath))
		if len(provider.Fields) == 0 {
			buffer.WriteString("\t\tFields: nil,\n")
		} else {
			buffer.WriteString("\t\tFields: []Field{\n")
			for _, field := range provider.Fields {
				fmt.Fprintf(&buffer, "\t\t\t{Key: %s, Kind: Kind%s},\n",
					strconv.Quote(field.Key), field.Kind)
			}
			buffer.WriteString("\t\t},\n")
		}
		buffer.WriteString("\t},\n")
	}
	buffer.WriteString("}\n")

	const outputPerm = 0o644
	err = os.WriteFile("fields_gen.go", buffer.Bytes(), outputPerm)
	if err != nil {
		return fmt.Errorf("writing fields_gen.go: %w", err)
	}
	return nil
}

type generatedProvider struct {
	Name     string
	Label    string
	DocsPath string
	Fields   []generatedField
}

type generatedField struct {
	Key  string
	Kind string
}

func extractFields(file *ast.File) (fields []generatedField, err error) {
	var newFunction *ast.FuncDecl
	for _, declaration := range file.Decls {
		function, ok := declaration.(*ast.FuncDecl)
		if ok && function.Name.Name == "New" && function.Body != nil {
			newFunction = function
			break
		}
	}
	if newFunction == nil {
		return nil, fmt.Errorf("no New function found")
	}

	structs := make(map[string]*ast.StructType)
	ast.Inspect(newFunction.Body, func(node ast.Node) bool {
		switch statement := node.(type) {
		case *ast.AssignStmt:
			if len(statement.Lhs) != 1 || len(statement.Rhs) != 1 {
				return true
			}
			identifier, ok := statement.Lhs[0].(*ast.Ident)
			if !ok {
				return true
			}
			composite, ok := statement.Rhs[0].(*ast.CompositeLit)
			if !ok {
				return true
			}
			structType, ok := composite.Type.(*ast.StructType)
			if ok {
				structs[identifier.Name] = structType
			}
		case *ast.DeclStmt:
			declaration, ok := statement.Decl.(*ast.GenDecl)
			if !ok {
				return true
			}
			for _, spec := range declaration.Specs {
				valueSpec, ok := spec.(*ast.ValueSpec)
				if !ok || len(valueSpec.Names) != 1 {
					continue
				}
				structType, ok := valueSpec.Type.(*ast.StructType)
				if ok {
					structs[valueSpec.Names[0].Name] = structType
				}
			}
		}
		return true
	})

	var targetName string
	ast.Inspect(newFunction.Body, func(node ast.Node) bool {
		call, ok := node.(*ast.CallExpr)
		if !ok || len(call.Args) != 2 {
			return true
		}
		selector, ok := call.Fun.(*ast.SelectorExpr)
		if !ok {
			return true
		}
		packageName, ok := selector.X.(*ast.Ident)
		if !ok || packageName.Name != "json" || selector.Sel.Name != "Unmarshal" {
			return true
		}
		dataIdentifier, ok := call.Args[0].(*ast.Ident)
		if !ok || dataIdentifier.Name != "data" {
			return true
		}
		unary, ok := call.Args[1].(*ast.UnaryExpr)
		if !ok || unary.Op != token.AND {
			return true
		}
		targetIdentifier, ok := unary.X.(*ast.Ident)
		if !ok {
			return true
		}
		targetName = targetIdentifier.Name
		return false
	})
	if targetName == "" {
		return nil, fmt.Errorf("no json.Unmarshal(data, ...) call found")
	}

	structType, ok := structs[targetName]
	if !ok {
		return nil, fmt.Errorf("struct type of %s not found", targetName)
	}

	for _, field := range structType.Fields.List {
		if len(field.Names) == 0 {
			continue
		}
		if field.Tag == nil {
			continue
		}
		tag, err := strconv.Unquote(field.Tag.Value)
		if err != nil {
			return nil, fmt.Errorf("unquoting tag: %w", err)
		}
		jsonTag, ok := reflect.StructTag(tag).Lookup("json")
		if !ok {
			continue
		}
		key, _, _ := strings.Cut(jsonTag, ",")
		if key == "" || key == "-" {
			continue
		}
		fields = append(fields, generatedField{
			Key:  key,
			Kind: kindOf(field.Type),
		})
	}
	return fields, nil
}

func kindOf(expression ast.Expr) (kind string) {
	switch typed := expression.(type) {
	case *ast.StarExpr:
		return kindOf(typed.X)
	case *ast.Ident:
		switch typed.Name {
		case "string":
			return "String"
		case "bool":
			return "Bool"
		case "int", "int8", "int16", "int32", "int64",
			"uint", "uint8", "uint16", "uint32", "uint64",
			"float32", "float64":
			return "Number"
		default:
			return "String"
		}
	case *ast.SelectorExpr:
		switch typed.Sel.Name {
		case "RawMessage":
			return "JSON"
		case "Prefix", "Addr":
			return "String"
		case "Regexp":
			return "String"
		default:
			return "String"
		}
	case *ast.ArrayType, *ast.MapType, *ast.InterfaceType, *ast.StructType:
		return "JSON"
	default:
		return "String"
	}
}
